/**
 * Writes src/data/intel.ts: one company-intel record per lead.
 *
 * Two inputs, both committed:
 *   research-2026-10-08/batches/*.json  every lead, with the 2026-08-24
 *                                       profile and the source labels
 *   research-2026-10-08/intel/<id>.json the full /company-intel pass, one file
 *                                       per company, where it has run
 *
 * A company with a 2026-10-08 file gets that. A company without one keeps its
 * 2026-08-24 profile, marked as that pass and never re-dated. Nothing here is
 * merged field-by-field across passes: a record is one dated read, whole.
 *
 * Run from app/: node scripts/5-emit-intel.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";

const DIR = "scripts/research-2026-10-08";
const OUT = "src/data/intel.ts";
const FIELDS = [
  "name", "description", "website", "location", "year_founded", "founder",
  "founder_linkedin", "founder_email", "funding_detail", "headcount",
  "past_completed_deals", "open_role", "contact_path",
];

const leads = readdirSync(`${DIR}/batches`)
  .filter((f) => f.endsWith(".json"))
  .flatMap((f) => JSON.parse(readFileSync(`${DIR}/batches/${f}`, "utf8")));

const arr = (v) => (Array.isArray(v) ? v : []);
const str = (v) => (v === undefined || v === null || v === "" ? null : String(v));

/** Keep only the keys the app's types know. Agents may add extra card keys. */
const pick = (o, keys) =>
  o && typeof o === "object"
    ? Object.fromEntries(keys.filter((k) => o[k] !== undefined && o[k] !== null && o[k] !== "").map((k) => [k, o[k]]))
    : null;
const PERSON = ["name", "title", "entity", "linkedin", "why", "caveat"];
const pickAll = (a, keys, must) => arr(a).map((x) => pick(x, keys)).filter((x) => x && x[must]);

function profileOf(p, fallbackName) {
  const out = {};
  for (const k of FIELDS) out[k] = str(p?.[k]);
  if (!out.name) out.name = fallbackName;
  return out;
}

let full = 0, prior = 0, none = 0;
const records = leads.flatMap((lead) => {
  const base = {
    companyId: lead.company_id,
    priority: lead.priority ?? null,
    fundingTier: lead.funding_tier ?? null,
    flags: arr(lead.flags),
  };
  const file = `${DIR}/intel/${lead.company_id}.json`;
  if (existsSync(file)) {
    const r = JSON.parse(readFileSync(file, "utf8"));
    if (r.company_id && r.company_id !== lead.company_id) {
      throw new Error(`${file}: company_id ${r.company_id} does not match`);
    }
    full++;
    return [{
      ...base,
      pass: "2026-10-08",
      full: true,
      verifiedOn: str(r.verified_on) ?? "2026-10-08",
      verifiedNote: str(r.verified_note),
      profile: profileOf(r.profile, lead.name),
      verdict: r.verdict?.kind ? pick(r.verdict, ["kind", "headline", "detail"]) : null,
      tagline: str(r.tagline),
      description: str(r.description) ?? str(r.profile?.description),
      stats: pickAll(r.stats, ["value", "label", "caveat"], "value").map((x) => ({ ...x, value: String(x.value) })),
      headlines: pickAll(r.headlines, ["date", "text", "source", "unconfirmed"], "text"),
      ownership: pickAll(r.ownership, ["entity", "detail", "since", "is_this", "is_former"], "entity"),
      deals: pickAll(r.deals, ["date", "name", "place"], "name"),
      footprint: r.footprint && typeof r.footprint === "object"
        ? { ...pick(r.footprint, ["hq", "bought", "branch", "customer"]), notes: pickAll(r.footprint.notes, ["state", "text"], "text") }
        : null,
      competitors: pickAll(r.competitors, ["name", "owner", "note", "is_acquired"], "name"),
      bestContact: r.best_contact?.name ? pick(r.best_contact, PERSON) : null,
      people: pickAll(r.people, PERSON, "name"),
      noneFound: arr(r.none_found),
      caveats: arr(r.caveats).filter((x) => typeof x === "string"),
      identityNote: str(r.identity_note),
      sources: arr(r.sources).filter((x) => typeof x === "string"),
    }];
  }
  // No intel at all: emit nothing. The UI says "no intel on file" rather than
  // showing an empty record dated as if a pass had run.
  if (!lead.prior_enrichment_2026_08_24) {
    none++;
    return [];
  }
  prior++;
  return [{
    ...base,
    pass: "2026-08-24",
    full: false,
    verifiedOn: "2026-08-24",
    verifiedNote: "earlier profile-only pass; not re-verified",
    profile: profileOf(lead.prior_enrichment_2026_08_24, lead.name),
    verdict: null, tagline: null, description: null, stats: [], headlines: [],
    ownership: [], deals: [], footprint: null, competitors: [],
    bestContact: null, people: [], noneFound: [], caveats: [],
    identityNote: null, sources: [],
  }];
});

writeFileSync(
  OUT,
  `/**
 * Company intel, one record per lead. GENERATED by scripts/5-emit-intel.mjs.
 * Do not hand-edit — re-run the generator.
 *
 *   ${full} leads carry the full /company-intel pass of 2026-10-08
 *   ${prior} carry only the earlier 2026-08-24 profile, labelled as such
 *   ${none} have no intel on file
 *
 * Every value traces to research-2026-10-08/. Nulls are honest gaps.
 */

import type { CompanyIntel } from "@/lib/types";

export const COMPANY_INTEL: CompanyIntel[] = ${JSON.stringify(records, null, 1)};
`,
);
console.log(`intel: ${leads.length} leads, ${records.length} records | full pass ${full} | prior only ${prior} | none ${none}`);
